export interface CoverageResult {
  coverageRate: number
  label: string
  notes: string[]
}

export function getCoverage(
  scheme: SchemeId,
  hospital: HospitalType,
  treatmentId: string,
): CoverageResult {
  const isBirth = treatmentId === 'natural-birth' || treatmentId === 'c-section'

  if (scheme === 'none') {
    return {
      coverageRate: 0,
      label: 'ชำระเงินเองทั้งหมด',
      notes: [
        'คนไทยทุกคนมีสิทธิรักษาพยาบาลอย่างน้อย 1 สิทธิ ตรวจสอบสิทธิฟรีที่สายด่วน 1330',
        'กรณีฉุกเฉินวิกฤต (UCEP) รักษาฟรีทุกโรงพยาบาล 72 ชั่วโมงแรก',
      ],
    }
  }

  if (scheme === 'ucs') {
    if (hospital === 'public-registered') {
      return {
        coverageRate: 1,
        label: 'สิทธิบัตรทองครอบคลุมเต็มจำนวน',
        notes: [
          'รักษาฟรีที่หน่วยบริการประจำตามสิทธิ ไม่เสียค่าใช้จ่าย',
          'ยาในบัญชียาหลักแห่งชาติไม่มีค่าใช้จ่ายเพิ่ม',
        ],
      }
    }
    if (hospital === 'public-other') {
      return {
        coverageRate: 0.9,
        label: 'ครอบคลุมเมื่อมีใบส่งตัวหรือเข้าเกณฑ์ 30 บาทรักษาทุกที่',
        notes: [
          'หากมีใบส่งตัวจากหน่วยบริการประจำ รักษาฟรีเต็มจำนวน',
          'นโยบาย 30 บาทรักษาทุกที่ ใช้บัตรประชาชนใบเดียวในจังหวัดนำร่อง',
          'หากไปเองโดยไม่มีใบส่งตัวและไม่ฉุกเฉิน อาจต้องจ่ายเองบางส่วน',
        ],
      }
    }
    return {
      coverageRate: 0,
      label: 'ไม่ครอบคลุมโรงพยาบาลเอกชน (ยกเว้นฉุกเฉินวิกฤต)',
      notes: [
        'เจ็บป่วยฉุกเฉินวิกฤต (UCEP) รักษาฟรี 72 ชั่วโมงแรกทุกโรงพยาบาล',
        'หลังพ้นวิกฤตจะถูกส่งตัวกลับโรงพยาบาลตามสิทธิ',
      ],
    }
  }

  if (scheme === 'sso') {
    if (hospital === 'public-registered') {
      const notes = [
        'รักษาฟรีที่โรงพยาบาลตามสิทธิ ไม่จำกัดจำนวนครั้งและวงเงิน',
      ]
      if (isBirth) {
        notes.push(
          'กรณีคลอดบุตร ได้รับเงินเหมาจ่าย 15,000 บาทต่อครั้ง และเงินสงเคราะห์หยุดงาน 50% ของค่าจ้าง 90 วัน',
        )
      }
      return {
        coverageRate: 1,
        label: 'สิทธิประกันสังคมครอบคลุมเต็มจำนวน',
        notes,
      }
    }
    if (hospital === 'public-other') {
      return {
        coverageRate: 0.7,
        label: 'ครอบคลุมบางส่วน (กรณีฉุกเฉินหรือส่งตัว)',
        notes: [
          'กรณีฉุกเฉิน เบิกคืนได้ตามอัตราที่ สปส. กำหนด',
          'หากมีใบส่งตัวจากโรงพยาบาลตามสิทธิ ครอบคลุมเต็มจำนวน',
        ],
      }
    }
    const notes = [
      'เจ็บป่วยฉุกเฉินวิกฤต (UCEP) รักษาฟรี 72 ชั่วโมงแรกทุกโรงพยาบาล',
      'กรณีไม่ฉุกเฉิน ต้องชำระเองแล้วเบิกคืนได้บางส่วนตามอัตราที่กำหนด',
    ]
    if (isBirth) {
      notes.push('ค่าคลอดบุตรเบิกเหมาจ่ายได้ 15,000 บาท ไม่ว่าคลอดที่ใด')
    }
    return {
      coverageRate: isBirth ? 0.25 : 0.1,
      label: 'ครอบคลุมจำกัด (เบิกคืนได้บางส่วน)',
      notes,
    }
  }

  // csmbs
  if (hospital === 'public-registered' || hospital === 'public-other') {
    return {
      coverageRate: 1,
      label: 'สวัสดิการข้าราชการเบิกได้ตามจริง',
      notes: [
        'รักษาที่โรงพยาบาลรัฐได้ทุกแห่ง ระบบเบิกจ่ายตรง ไม่ต้องสำรองจ่าย',
        'ค่าห้องพิเศษเบิกได้ตามเพดานที่กำหนด ส่วนเกินจ่ายเอง',
      ],
    }
  }
  return {
    coverageRate: 0.15,
    label: 'โรงพยาบาลเอกชนเบิกได้จำกัด',
    notes: [
      'เบิกได้เฉพาะกรณีฉุกเฉินวิกฤต หรือโครงการผ่าตัดนัดหมายที่ร่วมกับกรมบัญชีกลาง',
      'กรณีทั่วไปที่โรงพยาบาลเอกชน ต้องชำระเองเกือบทั้งหมด',
    ],
  }
}

export function formatBaht(n: number): string {
  return n.toLocaleString('th-TH', { maximumFractionDigits: 0 })
}
